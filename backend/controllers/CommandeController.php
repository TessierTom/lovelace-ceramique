<?php
declare(strict_types=1);

require_once __DIR__ . '/../views/JsonView.php';
require_once __DIR__ . '/../config/Database.php';

class CommandeController
{
    private PDO $db;

    public function __construct()
    {
        $this->db = Database::connect(); // ta classe de connexion existante
    }

    /**
     * Alias appelé par index.php [2] — route vers get().
     */
    public function index(): void
    {
        $this->get();
    }

    /**
     * GET /api/commande
     * Liste toutes les commandes avec le nom de l'utilisateur créateur.
     */
    public function get(): void
    {
        try {
            $stmt = $this->db->query(
                "SELECT c.id,
                        c.nom_client,
                        c.date_creation,
                        c.statut,
                        u.nom  AS utilisateur_nom
                 FROM commande c
                 JOIN utilisateur u ON u.id = c.utilisateur_id
                 ORDER BY c.date_creation DESC"
            );
            $rows = $stmt->fetchAll(PDO::FETCH_ASSOC);

            JsonView::success(
                200,
                $rows,
                count($rows) . ' commande(s) trouvée(s)'
            );
        } catch (PDOException $e) {
            JsonView::error(500, 'Erreur lors de la récupération des commandes', [], 'disconnected');
        }
    }

    /**
     * POST /api/commande
     * Crée une nouvelle commande.
     *
     * Corps attendu (JSON) :
     * {
     *   "nom_client"     : "Marie Dupont",
     *   "utilisateur_id" : 3
     * }
     *
     * Colonnes gérées automatiquement par la base [3] :
     *   - id            → GENERATED BY DEFAULT AS IDENTITY
     *   - date_creation → DEFAULT CURRENT_DATE
     *   - statut        → DEFAULT 'a_faire'
     */
    public function creer(): void
    {
        $input = json_decode(file_get_contents('php://input'), true);

        $nomClient     = trim($input['nom_client'] ?? '');
        $utilisateurId = (int)($input['utilisateur_id'] ?? 0);

        // --- Validation applicative ---
        if ($nomClient === '') {
            JsonView::error(400, 'Le champ nom_client est obligatoire');
            return;
        }
        if ($utilisateurId === 0) {
            JsonView::error(400, 'Le champ utilisateur_id est obligatoire');
            return;
        }

        // Vérification que l'utilisateur existe (FK [3])
        $check = $this->db->prepare("SELECT id FROM utilisateur WHERE id = :id");
        $check->execute([':id' => $utilisateurId]);
        if ($check->fetch() === false) {
            JsonView::error(422, 'L\'utilisateur indiqué n\'existe pas');
            return;
        }

        // --- Insertion ---
        try {
            $stmt = $this->db->prepare(
                "INSERT INTO commande (nom_client, utilisateur_id)
                 VALUES (:nom, :uid)
                 RETURNING id, nom_client, date_creation, statut"
            );
            $stmt->execute([
                ':nom' => $nomClient,
                ':uid' => $utilisateurId,
            ]);
            $new = $stmt->fetch(PDO::FETCH_ASSOC);

            JsonView::success(201, $new, 'Commande créée avec succès');
        } catch (PDOException $e) {
            JsonView::error(500, 'Erreur lors de la création de la commande', [], 'disconnected');
        }
    }
}